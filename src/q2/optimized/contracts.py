"""Immutable proposal, preparation and model evidence contracts."""
from dataclasses import dataclass
import json
import pickle

from q2.contracts import EncodedCandidate, LegalityRecord, ScoreRecord
from q2.evaluation import Incumbents


@dataclass(frozen=True)
class Proposal:
    candidate: EncodedCandidate
    family: str
    parent_signature: str | None = None
    region_ops: tuple[int, ...] = ()
    parameters_json: str = '{}'
    beta_stream: str | None = None
    beta: int | None = None

    @property
    def parameters(self):
        return json.loads(self.parameters_json)


@dataclass(frozen=True)
class ExecutionPreparation:
    execution_digest: str
    environment_digest: str
    tasks_blob: bytes
    cross_links_json: str
    traffic_json: str
    legality: LegalityRecord
    version: str = 'Q2-Preparation-1.0'

    @property
    def tasks(self):
        # Only locally generated bytes, never deserialize user-supplied pickle.
        return pickle.loads(self.tasks_blob)

    @property
    def cross_links(self):
        return json.loads(self.cross_links_json)

    @property
    def traffic(self):
        return json.loads(self.traffic_json)


@dataclass(frozen=True)
class ModelTrace:
    level: str
    raw_cycles: int
    score: ScoreRecord
    lower_bound: int
    pressure: float
    spill_bytes: int | None
    seconds: float
    events: int
    op_keys: tuple[tuple[int, int], ...] = ()
    starts: tuple[int, ...] = ()
    ends: tuple[int, ...] = ()

    def __post_init__(self):
        if self.level not in ('coarse', 'refined') or self.score.source != 'approximate':
            raise ValueError('model traces must remain approximate')
        if len(self.op_keys) != len(self.starts) or len(self.starts) != len(self.ends):
            raise ValueError('incomplete model operation trace')


@dataclass(frozen=True)
class OptimizationResult:
    incumbents: Incumbents
    stop_reason: str
    batches: int
    search_complete: bool
    beta_json: str
    statistics_json: str
